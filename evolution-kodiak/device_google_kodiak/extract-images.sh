# Generate vendor/google/kodiak-images from a Pixel 11 Pro XL factory image.
#
#   extract-images.sh <kodiak-*-factory-*.zip | image-kodiak-*.zip>
#
# Run from anywhere inside the Evolution X source tree. Replaces
# vendor/google/kodiak-images (except its .git). Its contents are Google's proprietary
# images: never push that directory to a public remote.
#
set -euo pipefail

MY_DIR="$(cd "$(dirname "$0")" && pwd -P)"
TOP="$(cd "$MY_DIR/../../.." && pwd -P)"
OUT="$TOP/vendor/google/kodiak-images"
UNPACK_BOOTIMG="$TOP/system/tools/mkbootimg/unpack_bootimg.py"

zip="$(realpath "$1")"
work="$(mktemp -d)"; trap 'rm -rf "$work"' EXIT

# Factory zips nest the partition images in image-<device>-<build>.zip
if unzip -Z1 "$zip" | grep -qE '(^|/)image-kodiak-.*\.zip$'; then
    inner="$(unzip -Z1 "$zip" | grep -E '(^|/)image-kodiak-.*\.zip$')"
    unzip -q -j "$zip" "$inner" -d "$work"
    image_zip="$work/$(basename "$inner")"
else
    image_zip="$zip"
fi
grep -q '^require board=.*kodiak' <(unzip -p "$image_zip" android-info.txt) ||
    { echo "not a kodiak image: $zip" >&2; exit 1; }
build_id="$(basename "$image_zip" .zip | sed 's/^image-kodiak-//')"

# Keep a local .git (if any) so regenerations show up as diffs
mkdir -p "$OUT"
find "$OUT" -mindepth 1 -maxdepth 1 ! -name .git -exec rm -rf {} +
mkdir -p "$OUT/images" "$OUT/radio" "$OUT/proprietary"

# Stock prebuilts that BoardConfig.mk points at
for img in boot dtbo system_dlkm vendor vendor_dlkm; do
    unzip -q -p "$image_zip" "$img.img" > "$OUT/images/$img.img"
done

# Raw OTA partitions (firmware + vendor_kernel_boot)
firmware=$(grep -vE '^(#|$)' "$MY_DIR/firmware.txt")
for part in $firmware; do
    unzip -q -p "$image_zip" "$part.img" > "$OUT/radio/$part.img"
    [[ -s "$OUT/radio/$part.img" ]] || { echo "missing $part.img" >&2; exit 1; }
done

# First-stage fstab and recovery init from the stock vendor_boot ramdisk
unzip -q -p "$image_zip" vendor_boot.img > "$work/vendor_boot.img"
python3 "$UNPACK_BOOTIMG" --boot_img "$work/vendor_boot.img" --out "$work/vb" >/dev/null
mkdir "$work/vb/root"
lz4 -dc "$work/vb/vendor_ramdisk00" | (cd "$work/vb/root" && cpio -id --quiet)
cp "$work/vb/root/first_stage_ramdisk/system/etc/fstab.malibu" "$OUT/proprietary/"
cp "$work/vb/root/init.recovery.malibu.rc" "$work/vb/root/init.recovery.kodiak.rc" "$OUT/proprietary/"

# USB PHY firmware: google-usb-phy.ko (a first-stage module in
# vendor_kernel_boot) loads it from the vendor ramdisk; without it first-stage
# init fails to load modules and reboots to the bootloader
mkdir -p "$OUT/proprietary/vendor_ramdisk/lib/firmware"
cp "$work/vb/root/lib/firmware/"usb_phy_fw*.bin "$OUT/proprietary/vendor_ramdisk/lib/firmware/"

# Recovery HALs (boot control for sideload slot switching, health for the
# battery check), as LineageOS's Pixel vendor trees ship them
recovery_hals="android.hardware.boot-service.default_recovery-pixel android.hardware.health-service.malibu_recovery"
mkdir -p "$OUT/proprietary/recovery/system/bin/hw" \
         "$OUT/proprietary/recovery/system/etc/init" \
         "$OUT/proprietary/recovery/system/etc/vintf/manifest"
for hal in $recovery_hals; do
    cp "$work/vb/root/system/bin/hw/$hal" "$OUT/proprietary/recovery/system/bin/hw/"
    cp "$work/vb/root/system/etc/init/$hal.rc" "$OUT/proprietary/recovery/system/etc/init/"
done
cp "$work/vb/root/system/etc/vintf/manifest/"android.hardware.{boot-service.default_recovery-pixel,health-service.malibu}.xml \
    "$OUT/proprietary/recovery/system/etc/vintf/manifest/"

{
    echo '#'
    echo '# Automatically generated by device/google/kodiak/extract-images.sh. DO NOT MODIFY'
    echo '#'
    echo
    echo 'LOCAL_PATH := $(call my-dir)'
    echo
    echo 'ifeq ($(TARGET_DEVICE),kodiak)'
    echo
    for part in $firmware; do
        echo "\$(call add-radio-file-sha1-checked,radio/$part.img,$(sha1sum "$OUT/radio/$part.img" | cut -d' ' -f1))"
    done
    echo
    echo 'endif'
} > "$OUT/Android.mk"

{
    echo '#'
    echo '# Automatically generated by device/google/kodiak/extract-images.sh. DO NOT MODIFY'
    echo '#'
    echo
    echo 'AB_OTA_PARTITIONS += \'
    for part in $firmware; do echo "    $part \\"; done | sed '$ s/ \\$//'
} > "$OUT/BoardConfigImages.mk"

{
    echo '//'
    echo '// Automatically generated by device/google/kodiak/extract-images.sh. DO NOT MODIFY'
    echo '//'
    echo
    echo 'soong_namespace {'
    echo '}'
    for hal in $recovery_hals; do
        bin="$OUT/proprietary/recovery/system/bin/hw/$hal"
        libs=$(readelf -d "$bin" | sed -n 's/.*Shared library: \[\(.*\)\.so\]/\1/p')
        echo
        echo 'cc_prebuilt_binary {'
        echo "    name: \"$hal\","
        echo '    owner: "google",'
        echo '    target: {'
        echo '        android_arm64: {'
        echo "            srcs: [\"proprietary/recovery/system/bin/hw/$hal\"],"
        echo '            shared_libs: ['
        for lib in $libs; do echo "                \"$lib\","; done
        echo '            ],'
        echo '        },'
        echo '    },'
        echo '    compile_multilib: "64",'
        echo '    strip: {'
        echo '        none: true,'
        echo '    },'
        echo '    prefer: true,'
        echo '    relative_install_path: "hw",'
        echo '    recovery: true,'
        echo '}'
    done
    for xml in "$OUT"/proprietary/recovery/system/etc/vintf/manifest/*.xml; do
        echo
        echo 'prebuilt_etc_xml {'
        echo "    name: \"kodiak_recovery_$(basename "$xml")\","
        echo '    owner: "google",'
        echo "    src: \"proprietary/recovery/system/etc/vintf/manifest/$(basename "$xml")\","
        echo '    filename_from_src: true,'
        echo '    sub_dir: "vintf/manifest",'
        echo '    recovery: true,'
        echo '}'
    done
} > "$OUT/Android.bp"

{
    echo '#'
    echo '# Automatically generated by device/google/kodiak/extract-images.sh. DO NOT MODIFY'
    echo '#'
    echo '# vendor, vendor_dlkm and system_dlkm ship as stock images (see'
    echo '# device/google/kodiak/BoardConfig.mk); only recovery blobs are listed here.'
    echo '#'
    echo
    echo 'PRODUCT_SOONG_NAMESPACES += vendor/google/kodiak-images'
    echo
    echo 'PRODUCT_COPY_FILES += \'
    for fw in "$OUT"/proprietary/vendor_ramdisk/lib/firmware/*; do
        fw="$(basename "$fw")"
        echo "    vendor/google/kodiak-images/proprietary/vendor_ramdisk/lib/firmware/$fw:\$(TARGET_COPY_OUT_VENDOR_RAMDISK)/lib/firmware/$fw \\"
        echo "    vendor/google/kodiak-images/proprietary/vendor_ramdisk/lib/firmware/$fw:\$(TARGET_COPY_OUT_VENDOR_RAMDISK)/first_stage_ramdisk/lib/firmware/$fw \\"
    done
    echo "    vendor/google/kodiak-images/proprietary/init.recovery.kodiak.rc:\$(TARGET_COPY_OUT_RECOVERY)/root/init.recovery.kodiak.rc \\"
    for hal in $recovery_hals; do
        echo "    vendor/google/kodiak-images/proprietary/recovery/system/etc/init/$hal.rc:\$(TARGET_COPY_OUT_RECOVERY)/root/system/etc/init/$hal.rc \\"
    done | sed '$ s/ \\$//'
    echo
    echo 'PRODUCT_PACKAGES += \'
    { for hal in $recovery_hals; do echo "$hal"; done
      for xml in "$OUT"/proprietary/recovery/system/etc/vintf/manifest/*.xml; do echo "kodiak_recovery_$(basename "$xml")"; done
    } | sed 's/^/    /; s/$/ \\/' | sed '$ s/ \\$//'
} > "$OUT/kodiak-images.mk"

(cd "$OUT" && find images radio proprietary -type f | sort | xargs sha256sum > SHA256SUMS)
echo "$build_id ($(basename "$zip"))" > "$OUT/SOURCE"
(cd "$OUT" && sha256sum -c --quiet SHA256SUMS)
echo "vendor/google/kodiak-images generated from $build_id: $(ls "$OUT/images" | wc -l) images, $(echo $firmware | wc -w) radio partitions"
